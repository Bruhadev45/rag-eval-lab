"""Write the legal-demo split report from the frozen data.

Run as a module::

    python -m rageval.legal_demo [--root PATH]

It reads ``<root>/data/legal-demo`` and overwrites two files in
``<root>/results/legal-demo``, so ``git diff`` shows any drift:

- ``splits.json`` -- split membership, counts, leakage groups and pins.
- ``SPLITS.md``   -- the same as Markdown tables, plus every case.

No retriever or model runs here. The output describes the frozen inputs that
later runs are scored against, and the historical ``results/`` files are
never touched.
"""

from __future__ import annotations

import argparse
import json
from collections.abc import Callable
from pathlib import Path

from .model import (
    CATEGORIES,
    MAX_CROSS_SPLIT_JACCARD,
    OUTCOMES,
    SPLITS,
    Case,
    Dataset,
    DatasetError,
    split_counts,
)
from .validate import load_dataset

ROOT = Path(__file__).resolve().parents[3]
OUT_DIR = Path("results") / "legal-demo"


def build_summary(dataset: Dataset) -> dict:
    """Everything ``splits.json`` holds, derived from ``dataset`` alone."""
    families: dict[str, set[str]] = {}
    for case in dataset.cases:
        for provision in dataset.provisions(case):
            families.setdefault(provision.split("#")[0], set()).add(case.split)
    jaccard, (first, second) = dataset.closest_cross_split
    return {
        "dataset": "legal-demo",
        "dataset_version": dataset.version,
        "fictional": True,
        "fixture_sha256": dataset.fixture_sha256,
        "cases_sha256": dataset.cases_sha256,
        "counts": split_counts(dataset.cases),
        "splits": {
            split: [qid for c in dataset.cases if c.split == split for qid in c.query_ids]
            for split in SPLITS
        },
        "leakage_groups": [
            {
                "split": group[0].split,
                "cases": [case.id for case in group],
                "issues": sorted({case.issue for case in group}),
                "provision_groups": sorted(
                    {dataset.provision_group_of[p] for c in group for p in dataset.provisions(c)}
                ),
            }
            for group in dataset.groups
        ],
        "families_in_several_splits": {
            family: [split for split in SPLITS if split in splits]
            for family, splits in sorted(families.items())
            if len(splits) > 1
        },
        "closest_cross_split_queries": {
            "query_ids": [first, second],
            "content_word_jaccard": round(jaccard, 4),
            "limit": MAX_CROSS_SPLIT_JACCARD,
        },
    }


def _count_table(dataset: Dataset, title: str, labels: tuple[str, ...], key: Callable) -> list[str]:
    def cell(cases: list[Case]) -> str:
        return f"{len(cases)} ({sum(len(c.queries) for c in cases)})" if cases else "-"

    rows = [f"| {title} | " + " | ".join(SPLITS) + " | all |", "|---" * (len(SPLITS) + 2) + "|"]
    for label in labels + ("**all**",):
        chosen = [c for c in dataset.cases if label == "**all**" or key(c) == label]
        cells = [cell([c for c in chosen if c.split == split]) for split in SPLITS]
        rows.append(f"| {label} | " + " | ".join(cells) + f" | {cell(chosen)} |")
    return rows + [""]


def render_markdown(dataset: Dataset, summary: dict) -> str:
    """``SPLITS.md``: counts, leakage groups, residual overlap and every case."""
    closest = summary["closest_cross_split_queries"]
    lines = [
        "# Legal demo: frozen evaluation splits",
        "",
        "Fictional data, not law and not legal advice. Generated by",
        "`python -m rageval.legal_demo` from `data/legal-demo/`; edits here are",
        "overwritten. No system has been scored on these splits yet.",
        "",
        f"- Dataset version: {summary['dataset_version']}",
        f"- Fixture: `{summary['fixture_sha256']}`",
        f"- Cases: `{summary['cases_sha256']}`",
        "",
        "## Cases (queries) per split",
        "",
        *_count_table(dataset, "Category", CATEGORIES, lambda c: c.category),
        *_count_table(dataset, "Expected outcome", OUTCOMES, lambda c: c.outcome),
        "## Leakage groups",
        "",
        "Cases that share an issue or a provision group stay in one split.",
        "",
        "| Split | Cases | Issues | Provision groups |",
        "|---|---|---|---|",
    ]
    for group in summary["leakage_groups"]:
        cells = (", ".join(group[key]) or "-" for key in ("cases", "issues", "provision_groups"))
        lines.append(f"| {group['split']} | " + " | ".join(cells) + " |")
    lines += ["", "## Residual overlap", ""]
    for family, splits in summary["families_in_several_splits"].items():
        lines.append(f"- `{family}` has provisions cited in {', '.join(splits)}.")
    lines += [
        (
            f"- Closest queries in different splits: `{closest['query_ids'][0]}` and "
            f"`{closest['query_ids'][1]}`, content-word Jaccard "
            f"{closest['content_word_jaccard']:.4f} (the check fails at {closest['limit']})."
        ),
        "",
        "## Cases",
        "",
        "| Case | Split | Category | Outcome | Requester | As of | First query |",
        "|---|---|---|---|---|---|---|",
    ]
    for case in dataset.cases:
        requester = case.tenant if case.matter is None else f"{case.tenant} / {case.matter}"
        query = case.queries[0].replace("|", r"\|")  # a pipe would end the table cell
        lines.append(
            f"| {case.id} | {case.split} | {case.category} | {case.outcome} | "
            f"{requester} | {case.as_of.isoformat()} | {query} |"
        )
    return "\n".join(lines) + "\n"


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="python -m rageval.legal_demo",
        description="Check the frozen legal-demo set and write its split report.",
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=ROOT,
        help="directory holding data/legal-demo (read) and results/legal-demo (written)",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> None:
    root = parse_args(argv).root
    try:
        dataset = load_dataset(root)
    except DatasetError as exc:
        raise SystemExit(f"rageval.legal_demo: error: {exc}") from exc
    summary = build_summary(dataset)
    out_dir = root / OUT_DIR
    outputs = {
        "splits.json": json.dumps(summary, indent=2, ensure_ascii=False) + "\n",
        "SPLITS.md": render_markdown(dataset, summary),
    }
    try:
        out_dir.mkdir(parents=True, exist_ok=True)
        for name, text in outputs.items():
            # newline="\n" keeps the bytes identical on Windows too.
            (out_dir / name).write_text(text, encoding="utf-8", newline="\n")
    except OSError as exc:
        raise SystemExit(
            f"rageval.legal_demo: error: cannot write {OUT_DIR} ({type(exc).__name__})"
        ) from exc
    counts = ", ".join(
        f"{split} {n['cases']} ({n['queries']})" for split, n in summary["counts"].items()
    )
    print(f"legal-demo v{dataset.version}: cases (queries) {counts}")
    print(f"wrote {OUT_DIR}/splits.json")
    print(f"wrote {OUT_DIR}/SPLITS.md")
