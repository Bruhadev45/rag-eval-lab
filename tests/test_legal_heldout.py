"""Tests for the held-out legal-demo ablation.

The committed outputs are regenerated byte for byte, every variant is checked
against the eligible pool on every case, and the paired statistics are checked
against hand-computed values. Like ``test_legal_live.py``, the output check
needs the ragfuse Git build pyproject pins, and any edit to the package needs a
rerun of both ``live`` and ``heldout`` before it passes again.
"""

