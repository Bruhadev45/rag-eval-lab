def test_committed_result_is_complete_and_honest() -> None:
    result = json.loads((REPO / OUT_DIR / "test-ablation.json").read_text())
    assert set(result["runs"]["test"]) == set(VARIANTS) == set(result["variants"])
    assert set(result["test_vs_bm25"]) == set(VARIANTS) - {"bm25"}
    assert result["provenance"]["model"]["kind"] == "none"
    assert not any("dense" in name for name in result["variants"])
    test_ids = {c.id for c in load_dataset(REPO).cases if c.split == "test"}
    for run in result["runs"]["test"].values():
        assert {r["case"] for r in run["per_query"]} == test_ids
        assert run["queries"] == 19
    for metrics in result["test_vs_bm25"].values():
        for stats in metrics.values():
            assert stats["cases"] == 7


