def test_readme_reports_the_committed_test_numbers() -> None:
    result = json.loads((REPO / OUT_DIR / "test-ablation.json").read_text())
    readme = " ".join((REPO / "README.md").read_text().split())
    bm25 = result["runs"]["test"]["bm25"]
    parent = result["test_vs_bm25"]["parent"]["rr"]
    assert f"recall {bm25['recall']}, MRR {bm25['rr']}" in readme
    assert f"sign-flip p = {parent['sign_flip_p']}" in readme
    assert "no learned-dense row" in readme
    runs = result["runs"]["test"]

    def kept(name):
        return [r["retrieved"] for r in runs[name]["per_query"]]

    def scores(name):
        return [(r.get("recall"), r.get("rr"), r.get("ndcg")) for r in runs[name]["per_query"]]

    assert all(kept(name) == kept("bm25") for name in ("tfidf", "hybrid", "rerank"))
    assert sum(a != b for a, b in zip(kept("graph"), kept("bm25"))) == 1
    assert scores("graph") == scores("bm25")
    assert "graph changes the passages of one query without changing any score" in readme
    kinds = [m["kind"] for m in runs["bm25"]["misses"]]
    assert kinds.count("at-ceiling") == 2 and kinds.count("ranking") == 2

    def missed(name):
        return [(m["query_id"], m["kind"]) for m in runs[name]["misses"]]

    assert all(missed(name) == missed("bm25") for name in runs)
    assert "two (one conflicting-source, one answerable) are ranking misses" in readme
    dev = result["runs"]["dev"]
    assert [n for n in dev if dev[n]["rr"] > dev["bm25"]["rr"]] == ["rerank"]
