"""Tests for the legal-demo live harness and its lexical retrievers.

Nothing here scores the test split: the held-out gate is exercised on a copy of
the set with its test cases removed. The retrievers are checked on hand-made
pools, eligibility on every case, query and configuration, and the committed
outputs are regenerated byte for byte. Those outputs hash every file of the
package, so any edit to it, a docstring included, needs a rerun of
``python -m rageval.legal_demo.live`` before this file passes again.
"""

