class _Dist:
    version = "0.2.0"

    def __init__(self, text: str | None) -> None:
        self.text = text

    def read_text(self, name: str) -> str | None:
        if self.text == "raise":
            raise OSError("unreadable")
        return self.text


@pytest.mark.parametrize(
    "text",
    [
        None,
        "raise",
        "{not json",
        "[]",
        '{"url": "file:///home/someone/ragfuse", "dir_info": {}}',
        '{"vcs_info": []}',
        '{"vcs_info": {"commit_id": 7}}',
        '{"vcs_info": {"commit_id": "/home/someone/ragfuse"}}',
        '{"vcs_info": {"commit_id": "b447cc3"}}',
    ],
)
def test_non_git_ragfuse_is_recorded_as_unknown_without_a_path(monkeypatch, text) -> None:
    monkeypatch.setattr(live_module.metadata, "distribution", lambda name: _Dist(text))
    assert live_module._ragfuse_build() == {"version": "0.2.0", "commit": "unknown"}


