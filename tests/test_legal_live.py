@pytest.mark.parametrize("ranker", [bm25, tfidf])
def test_rankers_return_only_matching_passages_best_first(ranker) -> None:
    pool = {"b": "hull inspection fee", "a": "hull inspection fee", "c": "berthing penalty"}
    ranked = ranker(pool, "hull inspection", 10)
    assert [pid for pid, _ in ranked] == ["a", "b"]  # equal scores tie-break on id
    assert ranked[0][1] == ranked[1][1] > 0
    assert ranker(pool, "hull inspection", 1) == ranked[:1]
    assert ranker(pool, "nothing shared", 10) == ()
    assert ranker({}, "hull", 10) == ()


def test_scores_match_hand_computed_values() -> None:
    pool = {"x": "hull hull inspection", "y": "inspection record"}
    # BM25, N=2, lengths 3 and 2, avg_len=2.5: idf(hull)=ln(1+1.5/1.5)=ln 2 and
    # idf(inspection)=ln(1+0.5/2.5)=ln 1.2. norm = 1.5*(0.25+0.75*len/2.5): 1.725 for
    # x and 1.275 for y. Each term adds idf * tf * 2.5 / (tf + norm).
    idf_hull, idf_insp = math.log(2), math.log(1.2)
    x = idf_hull * 2 * 2.5 / (2 + 1.725) + idf_insp * 2.5 / (1 + 1.725)
    y = idf_insp * 2.5 / (1 + 1.275)
    assert bm25(pool, "hull inspection", 2) == ((("x", round(x, 9))), ("y", round(y, 9)))
    # TF-IDF: idf(hull)=ln(3/2)+1, idf(inspection)=1; query "inspection" is the unit e_insp.
    hull = math.log(1.5) + 1
    assert tfidf(pool, "inspection", 2) == (
        ("y", round(1 / math.sqrt(1 + (math.log(1.5) + 1) ** 2), 9)),
        ("x", round(1 / math.sqrt(1 + (2 * hull) ** 2), 9)),
    )


def test_hybrid_weight_changes_the_fused_order(dataset, monkeypatch) -> None:
    case = _case(dataset, "ld-017")
    pool = sorted(eligible_passages(dataset, case))
    a, b = pool[0], pool[1]
    monkeypatch.setitem(live_module.RANKERS, "bm25", lambda p, q, d: ((a, 2.0), (b, 1.0)))
    monkeypatch.setitem(live_module.RANKERS, "tfidf", lambda p, q, d: ((b, 2.0), (a, 1.0)))
    leaning_bm25 = retrieve(dataset, case, "q", RunConfig("hybrid", 3, 2, 0.75))
    leaning_tfidf = retrieve(dataset, case, "q", RunConfig("hybrid", 3, 2, 0.25))
    assert (leaning_bm25, leaning_tfidf) == ((a, b), (b, a))


def test_bm25_prefers_the_rarer_term_and_tfidf_the_closer_text() -> None:
    pool = {"x": "hull hull inspection", "y": "inspection record", "z": "inspection"}
    assert bm25(pool, "hull inspection", 3)[0][0] == "x"
    assert tfidf(pool, "inspection", 3)[0][0] == "z"


def test_pools_hold_only_eligible_sections_and_never_a_trap(dataset) -> None:
    for case in dataset.cases:
        pool = eligible_passages(dataset, case)
        assert list(pool) == sorted(pool)
        for pid in pool:
            source_id, _, section_id = pid.partition("#")
            assert ineligibility(dataset.sources[source_id], case) == ()
            assert pool[pid] == dataset.sources[source_id].sections[section_id]
        assert not {ref.label for ref in case.traps} & set(pool)
        assert {ref.label for ref in case.evidence} <= set(pool)


def test_no_configuration_returns_an_ineligible_passage(dataset) -> None:
    for case in dataset.cases:
        pool = set(eligible_passages(dataset, case))
        for query in case.queries:
            for config in GRID:
                kept = retrieve(dataset, case, query, config)
                assert set(kept) <= pool
                assert len(kept) <= config.context_k


def _poisoned(monkeypatch, label: str) -> None:
    def rank(passages, query, depth):
        return ((label, 1.0),)

    monkeypatch.setitem(live_module.RANKERS, "bm25", rank)


def test_hybrid_fusion_refuses_a_candidate_outside_the_pool(dataset, monkeypatch) -> None:
    case = _case(dataset, "ld-001")
    _poisoned(monkeypatch, case.traps[0].label)
    with pytest.raises(IneligibleCandidateError):
        retrieve(dataset, case, case.queries[0], HYBRID)


def test_single_retriever_output_is_rechecked_against_the_pool(dataset, monkeypatch) -> None:
    case = _case(dataset, "ld-001")
    _poisoned(monkeypatch, case.traps[0].label)
    with pytest.raises(LiveRunError, match="outside the eligible pool"):
        retrieve(dataset, case, case.queries[0], BM25)


