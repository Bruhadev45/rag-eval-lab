def test_readme_numbers_match_the_committed_dev_run() -> None:
    result = json.loads((REPO / OUT_DIR / "dev-tuning.json").read_text())
    selected = result["tuning"]["selected_run"]
    ties = [
        row
        for row in result["tuning"]["grid"]
        if (row["recall"], row["mrr"]) == (selected["recall"], selected["mrr"])
    ]
    assert (selected["queries"], selected["scored"]) == (15, 7)
    assert (selected["recall"], selected["mrr"], len(ties)) == (1.0, 0.9286, 40)
    assert max(r["eligible"] for r in selected["per_query"]) == 7
    shapes: dict[tuple[int, int], set[tuple]] = {}
    for row in result["tuning"]["grid"]:
        c = row["config"]
        if c["system"] == "hybrid":
            metrics = (row["recall"], row["mrr"], row["ndcg"])
            shapes.setdefault((c["depth"], c["context_k"]), set()).add(metrics)
    assert len(shapes) == 11 and all(len(rows) == 1 for rows in shapes.values())
    readme = " ".join((REPO / "README.md").read_text().split())
    assert "40 of the 55 configurations tie at recall 1.0 and MRR 0.9286" in readme
    assert "All three fusion weights tie, so dev does not identify a fusion weight" in readme
