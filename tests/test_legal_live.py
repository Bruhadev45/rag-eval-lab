def _copy_repo(tmp_path: Path) -> Path:
    shutil.copytree(REPO / "data" / "legal-demo", tmp_path / "data" / "legal-demo")
    return tmp_path


@pytest.mark.skipif(not PINNED_BUILD, reason="ragfuse is not the Git build pyproject pins")
def test_cli_rewrites_the_committed_outputs_byte_for_byte(tmp_path, capsys, monkeypatch) -> None:
    calls = []

    def spy(dataset, config, split, **kwargs):
        calls.append((split, kwargs))
        return real(dataset, config, split, **kwargs)

    real = live_module.evaluate
    monkeypatch.setattr(live_module, "evaluate", spy)
    root = _copy_repo(tmp_path)
    main(["--root", str(root)])
    assert calls == [("dev", {})] * len(GRID)
    for name in ("dev-tuning.json", "DEV_TUNING.md"):
        fresh = (root / OUT_DIR / name).read_bytes()
        assert fresh == (REPO / OUT_DIR / name).read_bytes(), name
        assert str(tmp_path).encode() not in fresh
    assert "ran 55 configurations on dev" in capsys.readouterr().out
    result = json.loads((root / OUT_DIR / "dev-tuning.json").read_text())
    assert result["tuning"]["split"] == "dev"
    dev_ids = {c.id for c in load_dataset(REPO).cases if c.split == "dev"}
    per_query = result["tuning"]["selected_run"]["per_query"]
    assert {r["query_id"].split(".")[0] for r in per_query} <= dev_ids


